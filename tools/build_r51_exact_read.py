#!/usr/bin/env python3
"""Build and validate the R51.1 publication metadata, using local files only.

This is the active release builder, superseding build_r50_crawler_contract.py.
It does not execute a mathematical verifier or rewrite scientific payloads.
Only HTML href attributes, canonical tags, and application/ld+json blocks are
normalized; executable JavaScript, including the archived implementation, is
never rewritten.

Run:
    python3 -I tools/build_r51_exact_read.py
    python3 -I tools/build_r51_exact_read.py --validate-only

The final write is SHA256SUMS. Validation after that write is read-only.
"""

