AUDIT_IDS = {"B-2", "S-5/05a", "W-0", "W-1", "NDA-3"}
SITEMAP_NS = "http://www.sitemaps.org/schemas/sitemap/0.9"
REDIRECT_HEADER = "# R51 canonical aliases; generated by tools/build_r51_exact_read.py."
HREF_RE = re.compile(
    r"""(?P<lead>(?P<attribute>[^\s<>=/"']+)\s*=\s*)(?:"(?P<double>[^"]*)"|'(?P<single>[^']*)'|(?P<bare>[^\s>]+))""",
    re.IGNORECASE,
)
URL_KEYS = {
    "@id", "url", "contentUrl", "embedUrl", "thumbnailUrl", "sameAs",
    "mainEntityOfPage", "isPartOf", "hasPart", "license", "citation",
}


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def digest(path: Path) -> str:
    require(path.is_file(), f"Missing file: {path.relative_to(ROOT)}")
    result = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            result.update(chunk)
    return result.hexdigest()


def read_json(relative: str) -> dict:
    value = json.loads((ROOT / relative).read_text(encoding="utf-8"))
    require(isinstance(value, dict), f"Expected JSON object: {relative}")
    return value


def json_bytes(value: object) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def write_changed(path: Path, data: bytes | str) -> bool:
    encoded = data.encode("utf-8") if isinstance(data, str) else data
    if path.exists() and path.read_bytes() == encoded:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encoded)
    return True


def url_path(relative: str) -> str:
    return "/" + quote(relative, safe="/-._~")


def absolute_file_url(relative: str) -> str:
    return BASE + url_path(relative)


def local_reference(reference: str) -> Path:
    """Resolve a site-root-relative artifact reference without network access."""
    parsed = urlsplit(reference)
    require(
        not parsed.netloc or parsed.netloc == urlsplit(BASE).netloc,
        f"Cannot locally verify external reference: {reference}",
    )
    require(parsed.scheme in {"", "http", "https"}, f"Invalid reference: {reference}")
    path = (ROOT / unquote(parsed.path).lstrip("/")).resolve()
    require(path.is_relative_to(ROOT), f"Reference leaves site root: {reference}")
    return path


def payload_files() -> list[Path]:
    files = []
    for path in sorted(ROOT.rglob("*")):
        if "__pycache__" in path.relative_to(ROOT).parts:
            continue
        require(not path.is_symlink(), f"Symlink is not a release payload: {path}")
        if path.is_file() and path != ROOT / "SHA256SUMS":
            relative = path.relative_to(ROOT).as_posix()
            require("\n" not in relative and "\r" not in relative,
                    f"Unsupported newline in payload filename: {relative!r}")
            files.append(path)
    return files


def canonical_route(path: Path) -> str:
    relative = path.relative_to(ROOT).as_posix()
    if relative in {"architecture.html", "architecture/index.html"}:
        return "/architecture"
    if relative == "index.html":
        return "/"
    if relative.endswith("/index.html"):
        return url_path(relative[:-len("index.html")])
    return url_path(relative[:-len(".html")])


def page_inventory() -> tuple[list[Path], dict[str, Path], dict[str, str]]:
    pages = [
        p for p in sorted(ROOT.rglob("*.html"))
        if "?" not in p.name and "__pycache__" not in p.relative_to(ROOT).parts
    ]
    groups: dict[str, list[Path]] = defaultdict(list)
    aliases = {}
    for page in pages:
        route = canonical_route(page)
        groups[route].append(page)
        aliases[unquote(url_path(page.relative_to(ROOT).as_posix()))] = route
        aliases[unquote(route)] = route
    owners = {}
    for route, paths in groups.items():
        if len(paths) > 1:
            require(
                route == "/architecture"
                and {p.relative_to(ROOT).as_posix() for p in paths}
                == {"architecture.html", "architecture/index.html"},
                f"Undeclared duplicate canonical route: {route}",
            )
            owners[route] = ROOT / "architecture.html"
        else:
            owners[route] = paths[0]
    aliases["/architecture/"] = "/architecture"
    return pages, owners, aliases


class Page(HTMLParser):
    """Retain exact source spans so unrelated markup and scripts remain intact."""

    def __init__(self, text: str):
        super().__init__(convert_charrefs=False)
        self.text = text
        self.offsets = [0]
        for match in re.finditer("\n", text):
            self.offsets.append(match.end())
        self.tags: list[tuple[int, int, str, str, dict]] = []
        self.json_spans: list[tuple[int, int]] = []
        self.json_start: int | None = None
        self.feed(text)
        self.close()

    def source_offset(self) -> int:
        line, column = self.getpos()
        return self.offsets[line - 1] + column

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        raw = self.get_starttag_text()
        start = self.source_offset()
        attributes = {key.lower(): value for key, value in attrs}
        self.tags.append((start, start + len(raw), raw, tag.lower(), attributes))
        if tag.lower() == "script" and (
            attributes.get("type") or ""
        ).lower().split(";", 1)[0].strip() == "application/ld+json":
            self.json_start = start + len(raw)

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.handle_starttag(tag, attrs)
        if tag.lower() == "script":
            self.json_start = None

    def handle_endtag(self, tag: str) -> None:
        if tag.lower() == "script" and self.json_start is not None:
            self.json_spans.append((self.json_start, self.source_offset()))
            self.json_start = None

    def canonical_tags(self) -> list[tuple]:
        return [
            item for item in self.tags
            if item[3] == "link" and "canonical" in
            (item[4].get("rel") or "").lower().split()
        ]

    def noindex(self) -> bool:
        return any(
            tag == "meta"
            and (attrs.get("name") or "").lower() in {"robots", "googlebot", "bingbot"}
            and "noindex" in re.split(r"[\s,;]+", (attrs.get("content") or "").lower())
            for _, _, _, tag, attrs in self.tags
        )


def normalized_html_url(
    value: str, page: Path, aliases: dict[str, str], *, absolute: bool,
) -> str:
    if not value or (value.startswith("#") and not absolute):
        return value
    source_url = absolute_file_url(page.relative_to(ROOT).as_posix())
    parsed = urlsplit(urljoin(source_url, value))
    if parsed.scheme not in {"http", "https"} or parsed.netloc != urlsplit(BASE).netloc:
        return value
    route = aliases.get(unquote(parsed.path or "/"))
    if route is None:
        return value
    prefix = urlsplit(BASE) if absolute else None
    return urlunsplit((
        prefix.scheme if prefix else "",
        prefix.netloc if prefix else "",
        route,
        parsed.query,
        parsed.fragment,
    ))


def normalized_jsonld(value: object, page: Path, aliases: dict[str, str], key: str = ""):
    if isinstance(value, dict):
        return {k: normalized_jsonld(v, page, aliases, k) for k, v in value.items()}
    if isinstance(value, list):
        return [normalized_jsonld(v, page, aliases, key) for v in value]
    if isinstance(value, str) and (
        key in URL_KEYS or value.startswith(("http:", "https:", "//", "/", "#", "./", "../"))
    ):
        return normalized_html_url(value, page, aliases, absolute=True)
    return value


def normalize_html(pages: list[Path], aliases: dict[str, str]) -> int:
    changed = 0
    for path in pages:
        text = path.read_text(encoding="utf-8")
        parsed = Page(text)
        canonical = BASE + canonical_route(path)
        canonical_tags = parsed.canonical_tags()
        require(len(canonical_tags) <= 1, f"Multiple canonical tags: {path}")
        patches = []
        for start, end, raw, tag, attrs in parsed.tags:
            if tag == "link" and "canonical" in (attrs.get("rel") or "").lower().split():
                new = f'<link rel="canonical" href="{html.escape(canonical, quote=True)}">'
            else:
                def rewrite_href(match):
                    # Consume every quoted attribute as one token. A string
                    # inside onclick/data-* must never be mistaken for href.
                    if match.group("attribute").lower() != "href":
                        return match.group(0)
                    original = next(
                        match.group(name) for name in ("double", "single", "bare")
                        if match.group(name) is not None
                    )
                    value = html.unescape(original)
                    updated = normalized_html_url(value, path, aliases, absolute=False)
                    if updated == value:
                        return match.group(0)
                    return match.group("lead") + '"' + html.escape(updated, quote=True) + '"'
                new = HREF_RE.sub(rewrite_href, raw)
            if new != raw:
                patches.append((start, end, new))
        if not canonical_tags:
            closing_head = re.search(r"</head\s*>", text, flags=re.IGNORECASE)
            require(closing_head is not None, f"Missing closing head: {path}")
            patches.append((
                closing_head.start(), closing_head.start(),
                f'  <link rel="canonical" href="{canonical}">\n',
            ))
        for start, end in parsed.json_spans:
            source = text[start:end]
            value = json.loads(source)
            updated = normalized_jsonld(value, path, aliases)
            if updated != value:
                patches.append((start, end, "\n" + json.dumps(updated, indent=2, ensure_ascii=False) + "\n"))
        patches.sort(reverse=True)
        previous_start = len(text) + 1
        for start, end, value in patches:
            require(end <= previous_start, f"Overlapping HTML edits: {path}")
            text = text[:start] + value + text[end:]
            previous_start = start
        changed += write_changed(path, text)
    return changed


def redirect_map(pages: list[Path]) -> dict[str, str]:
    redirects = {
        url_path(p.relative_to(ROOT).as_posix()): canonical_route(p) for p in pages
    }
    return {source: target for source, target in redirects.items() if source != target}


def validate_redirect_graph(redirects: dict[str, str]) -> None:
    # Netlify matches redirect paths after trailing-slash normalization.
    # A slash-only forced redirect therefore matches its own destination.
    normalized = {}
    for source, target in redirects.items():
        source_key = source.rstrip("/") or "/"
        target_key = target.rstrip("/") or "/"
        require(source_key not in normalized,
                f"Duplicate redirect source after slash normalization: {source}")
        require(source_key != target_key,
                f"Redirect self-loop after slash normalization: {source} -> {target}")
        normalized[source_key] = target_key
    for source, target in normalized.items():
        require(target not in normalized,
                f"Redirect loop or chain after slash normalization: {source} -> {target}")


def write_redirects(redirects: dict[str, str]) -> None:
    path = ROOT / "_redirects"
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        require(
            not existing.strip() or existing.startswith(REDIRECT_HEADER),
            "Existing _redirects is not owned by this builder; preserve its rules explicitly.",
        )
    text = REDIRECT_HEADER + "\n"
    text += "# Explicit file aliases only; folder slash conventions are otherwise preserved.\n"
    text += "".join(f"{source}  {target}  301!\n" for source, target in sorted(redirects.items()))
    write_changed(path, text)


def hash_bindings(value: object, location: str = ""):
    if isinstance(value, dict):
        for key, expected in value.items():
            if key == "sha256":
                reference = value.get("url", value.get("path"))
                require(reference is not None, f"Hash lacks a reference at {location}.{key}")
                yield f"{location}.{key}", reference, expected
            elif key.endswith("_sha256"):
                stem = key[:-len("_sha256")]
                reference = value.get(stem + "_url", value.get(stem + "_path"))
                require(reference is not None, f"Hash lacks its paired reference at {location}.{key}")
                yield f"{location}.{key}", reference, expected
            if isinstance(expected, (dict, list)):
                yield from hash_bindings(expected, f"{location}.{key}")
    elif isinstance(value, list):
        for index, item in enumerate(value):
            yield from hash_bindings(item, f"{location}[{index}]")


def verify_hash_bindings(value: object, label: str) -> int:
    count = 0
    for location, reference, expected in hash_bindings(value, label):
        require(isinstance(expected, str) and re.fullmatch(r"[0-9a-f]{64}", expected) is not None,
                f"Invalid SHA-256 at {location}")
        actual = digest(local_reference(reference))
        require(actual == expected, f"Hash mismatch: {location}: {reference}: {actual}")
        count += 1
    return count


def refresh_exact_registry() -> None:
    registry = read_json(EXACT_REGISTRY)
    matches = [r for r in registry["records"] if r["id"] == "CA-ALG-001"]
    require(len(matches) == 1, "Expected exactly one CA-ALG-001 record.")
    procedure = matches[0]["procedure"]
    require(
        local_reference(procedure["implementation_url"]) == ROOT / "exact/exact-reader.js",
        "CA-ALG-001 implementation path changed unexpectedly.",
    )
    procedure["implementation_sha256"] = digest(ROOT / "exact/exact-reader.js")
    # Every other current and historical binding is asserted, never rewritten.
    verify_hash_bindings(registry, EXACT_REGISTRY)
    write_changed(ROOT / EXACT_REGISTRY, json_bytes(registry))


def verify_audit_records(manifest: dict) -> int:
    registry = read_json(PUBLIC_REGISTRY)
    sources = {r["id"]: r for r in registry["artifacts"]}
    records = {r["id"]: r for r in manifest["records"]}
    require(set(sources) == set(records) == AUDIT_IDS, "Released audit record identities changed.")
    count = 0
    for identifier, record in records.items():
        source = sources[identifier]
        for key in ("id", "label", "result", "command", "scope"):
            require(record[key] == source[key], f"Scientific field changed: {identifier}.{key}")
        require(
            local_reference(record["artifact"]["url"])
            == local_reference(source["artifact"]),
            f"Artifact reference changed: {identifier}",
        )
        require(record["artifact"]["sha256"] == source["sha256"],
                f"Artifact declared hash changed: {identifier}")
        verify_hash_bindings(record["artifact"], identifier + ".artifact")
        verify_hash_bindings(
            {key: value for key, value in record["receipt"].items() if key != "archive_member"},
            identifier + ".receipt",
        )
        archive = local_reference(record["artifact"]["url"])
        receipt = local_reference(record["receipt"]["url"])
        member = record["receipt"]["archive_member"]
        with zipfile.ZipFile(archive) as package:
            require(member in package.namelist(), f"Missing archive receipt: {identifier}: {member}")
            require(package.read(member) == receipt.read_bytes(),
                    f"Public receipt differs from archive member: {identifier}")
        count += 1
    require(manifest["next_records"] == registry["next_records"], "Next-record list changed.")
    return count


def make_manifest(issued: str) -> dict:
    previous = read_json(OLD_MANIFEST)
    verify_audit_records(previous)
    require(
        digest(ROOT / OLD_CONTRACT) == previous["reader_contract"]["sha256"],
        "Archived reader contract does not match the hash in manifest v0.1.",
    )
    manifest = copy.deepcopy(previous)
    manifest["version"] = "v0.2"
    manifest["issued"] = issued
    manifest["website_release"] = WEBSITE_RELEASE
    manifest["publisher"]["url"] = BASE + "/anthony-vito-coppa"
    for key, relative in (
        ("claim_registry", PUBLIC_REGISTRY),
        ("reader_contract", CONTRACT),
        ("exact_reader_registry", EXACT_REGISTRY),
        ("registry_index", REGISTRY_INDEX),
    ):
        manifest[key] = {"url": absolute_file_url(relative), "sha256": digest(ROOT / relative)}
    manifest["historical_bindings"] = [{
        "manifest": {
            "url": absolute_file_url(OLD_MANIFEST),
            "sha256": digest(ROOT / OLD_MANIFEST),
        },
        "reader_contract": {
            "url": absolute_file_url(OLD_CONTRACT),
            "sha256": previous["reader_contract"]["sha256"],
        },
        "original_reader_contract_url": previous["reader_contract"]["url"],
        "status": "byte_preserved_historical_manifest",
        "rule": "The archived contract supplies the exact bytes named by the unchanged v0.1 hash. The original mutable contract URL now serves its current version.",
    }]
    manifest["publication_builder"] = {
        "url": absolute_file_url(BUILDER),
        "sha256": digest(ROOT / BUILDER),
        "supersedes": absolute_file_url("tools/build_r50_crawler_contract.py"),
        "scope": "Local URL normalization and publication-integrity checks; scientific verifiers are not executed.",
    }
    return manifest


def sitemap_entries(owners: dict[str, Path]) -> tuple[set[str], int]:
    urls = {
        BASE + route for route, path in owners.items()
        if not Page(path.read_text(encoding="utf-8")).noindex()
    }
    pdf_groups: dict[str, list[Path]] = defaultdict(list)
    for path in sorted(ROOT.rglob("*")):
        if (
            path.is_file() and path.suffix.lower() == ".pdf" and "?" not in path.name
            and "__pycache__" not in path.relative_to(ROOT).parts
        ):
            pdf_groups[digest(path)].append(path)
    duplicates = 0
    for paths in pdf_groups.values():
        # Existing lowercase public names take precedence over byte-identical aliases.
        chosen = min(paths, key=lambda p: (
            p.relative_to(ROOT).as_posix() != p.relative_to(ROOT).as_posix().lower(),
            len(p.relative_to(ROOT).as_posix()),
            p.relative_to(ROOT).as_posix(),
        ))
        urls.add(absolute_file_url(chosen.relative_to(ROOT).as_posix()))
        duplicates += len(paths) - 1
    return urls, duplicates


def write_sitemap(urls: set[str]) -> None:
    ET.register_namespace("", SITEMAP_NS)
    root = ET.Element(f"{{{SITEMAP_NS}}}urlset")
    for url in sorted(urls):
        node = ET.SubElement(root, f"{{{SITEMAP_NS}}}url")
        ET.SubElement(node, f"{{{SITEMAP_NS}}}loc").text = url
    # Extraction/build mtimes do not establish content-modification dates.
    write_changed(ROOT / "sitemap.xml", ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n")


def validate_routes(pages, owners, aliases) -> dict:
    noindex_count = 0
    for path in pages:
        parsed = Page(path.read_text(encoding="utf-8"))
        canonicals = parsed.canonical_tags()
        require(len(canonicals) == 1, f"Expected one canonical link: {path}")
        require(canonicals[0][4].get("href") == BASE + canonical_route(path),
                f"Incorrect canonical URL: {path}")
        noindex_count += parsed.noindex()
        for _, _, _, tag, attrs in parsed.tags:
            if "href" not in attrs or attrs["href"] is None:
                continue
            if tag == "link" and "canonical" in (attrs.get("rel") or "").lower().split():
                continue
            value = attrs["href"]
            require(
                normalized_html_url(value, path, aliases, absolute=False) == value,
                f"Noncanonical internal HTML href: {path.relative_to(ROOT)}: {value}",
            )
        for start, end in parsed.json_spans:
            value = json.loads(parsed.text[start:end])
            require(normalized_jsonld(value, path, aliases) == value,
                    f"Noncanonical JSON-LD URL: {path.relative_to(ROOT)}")
    redirects = {}
    for number, line in enumerate((ROOT / "_redirects").read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = line.split()
        require(len(parts) == 3 and parts[2] == "301!",
                f"Unexpected redirect rule on line {number}")
        source, target, _ = parts
        require(source not in redirects, f"Duplicate redirect source: {source}")
        redirects[source] = target
    require(redirects == redirect_map(pages), "Redirect inventory differs from canonical aliases.")
    validate_redirect_graph(redirects)
    for source, target in redirects.items():
        require(target in owners and owners[target].is_file(),
                f"Redirect target does not resolve locally: {target}")
    expected, pdf_duplicates = sitemap_entries(owners)
    tree = ET.parse(ROOT / "sitemap.xml")
    require(tree.getroot().tag == f"{{{SITEMAP_NS}}}urlset", "Invalid sitemap root.")
    nodes = tree.findall(f"{{{SITEMAP_NS}}}url")
    actual = [node.findtext(f"{{{SITEMAP_NS}}}loc") for node in nodes]
    require(len(actual) == len(set(actual)), "Duplicate sitemap URL.")
    require(set(actual) == expected, "Sitemap differs from indexable HTML and unique PDFs.")
    require(not tree.findall(f".//{{{SITEMAP_NS}}}lastmod"), "Unproven sitemap lastmod values.")
    for url in actual:
        route = urlsplit(url).path
        path = owners.get(route, local_reference(url))
        require(path.is_file(), f"Sitemap target is missing: {url}")
    return {
        "html_files": len(pages),
        "canonical_html_routes": len(owners),
        "explicit_noindex_html_files": noindex_count,
        "redirects": len(redirects),
        "sitemap_urls": len(actual),
        "byte_identical_pdf_aliases_omitted": pdf_duplicates,
    }


def validate_integrity() -> dict:
    current = read_json(NEW_MANIFEST)
    require(current["version"] == "v0.2", "Current manifest is not v0.2.")
    original = read_json(OLD_MANIFEST)
    require(current["records"] == original["records"], "Released scientific audit records changed.")
    count = verify_audit_records(current)
    for key, relative in (
        ("claim_registry", PUBLIC_REGISTRY), ("reader_contract", CONTRACT),
        ("exact_reader_registry", EXACT_REGISTRY), ("registry_index", REGISTRY_INDEX),
    ):
        require(local_reference(current[key]["url"]) == ROOT / relative,
                f"Manifest points to unexpected {key}.")
    manifest_hashes = verify_hash_bindings(current, NEW_MANIFEST)
    history = current["historical_bindings"]
    require(len(history) == 1, "Unexpected historical manifest inventory.")
    require(local_reference(history[0]["manifest"]["url"]) == ROOT / OLD_MANIFEST,
            "Historical manifest path changed.")
    require(local_reference(history[0]["reader_contract"]["url"]) == ROOT / OLD_CONTRACT,
            "Historical reader contract path changed.")
    require(history[0]["reader_contract"]["sha256"] == original["reader_contract"]["sha256"],
            "Historical contract binding was replaced.")
    exact_hashes = verify_hash_bindings(read_json(EXACT_REGISTRY), EXACT_REGISTRY)
    return {
        "released_audit_packages": count,
        "public_receipts_equal_archive_members": count,
        "manifest_hash_bindings": manifest_hashes,
        "exact_current_and_historical_hash_bindings": exact_hashes,
        "historical_manifest_and_contract": "PASS",
    }


def write_checksums() -> int:
    files = payload_files()
    text = "".join(f"{digest(path)}  ./{path.relative_to(ROOT).as_posix()}\n" for path in files)
    write_changed(ROOT / "SHA256SUMS", text)
    return len(files)


def validate_checksums() -> int:
    expected = {p.relative_to(ROOT).as_posix(): digest(p) for p in payload_files()}
    recorded = {}
    for number, line in enumerate((ROOT / "SHA256SUMS").read_text(encoding="utf-8").splitlines(), 1):
        parts = line.split("  ", 1)
        require(len(parts) == 2, f"Malformed SHA256SUMS line {number}")
        checksum, name = parts
        name = name.removeprefix("./")
        require(name not in recorded, f"Duplicate checksum path: {name}")
        recorded[name] = checksum
    require(recorded.keys() == expected.keys(), "SHA256SUMS payload inventory differs.")
    failures = [name for name in expected if recorded[name] != expected[name]]
    require(not failures, "SHA256SUMS mismatches: " + ", ".join(failures))
    return len(expected)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--validate-only", action="store_true", help="Read and check; write no files.")
    parser.add_argument("--issued", default=RELEASE_DATE, help="Declared release date, YYYY-MM-DD.")
    args = parser.parse_args()
    require(re.fullmatch(r"\d{4}-\d{2}-\d{2}", args.issued) is not None, "Invalid issued date.")
    pages, owners, aliases = page_inventory()
    summary = {"mode": "validate" if args.validate_only else "build", "website_release": WEBSITE_RELEASE}
    if not args.validate_only:
        # Preflight released archive and historical bindings before editing metadata.
        previous = read_json(OLD_MANIFEST)
        verify_audit_records(previous)
        require(digest(ROOT / OLD_CONTRACT) == previous["reader_contract"]["sha256"],
                "Historical contract archive is missing or has changed.")
        summary["html_files_changed"] = normalize_html(pages, aliases)
        write_redirects(redirect_map(pages))
        refresh_exact_registry()
        write_changed(ROOT / NEW_MANIFEST, json_bytes(make_manifest(args.issued)))
        urls, _ = sitemap_entries(owners)
        write_sitemap(urls)
        summary.update(validate_routes(pages, owners, aliases))
        summary.update(validate_integrity())
        write_checksums()  # Deliberately the final payload write.
    else:
        summary.update(validate_routes(pages, owners, aliases))
        summary.update(validate_integrity())
    summary["sha256sum_payload_files"] = validate_checksums()
    summary["result"] = "PASS"
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0


