#!/usr/bin/env python3
"""Build and validate R52 discovery metadata without rewriting science.

R52 adds static paper records and machine-readable discovery routes.  It
preserves the R51.1 verification manifest and all source-owned artifacts.

Run:
    python3 -I tools/build_r52_discovery.py
    python3 -I tools/build_r52_discovery.py --validate-only
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit
from xml.etree import ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
BASE = "https://eulershiddenl.ink"
RELEASE = "R52"
LASTMOD_SOURCE = "research/sitemap-lastmod-r52.json"
REDIRECT_HEADER = "# R52 canonical aliases; generated by tools/build_r52_discovery.py."
PAPERS = {
    "/papers/four-dual-forms/gravity-light": {
        "file": "papers/four-dual-forms/gravity-light.html",
        "title": "Gravity Light: Metric Invariance and Fixed Null Directions",
        "pdf": "papers/four-dual-forms/pdf/01_gravity_light.pdf",
        "source": "papers/four-dual-forms/source/01_gravity_light.tex",
    },
    "/papers/four-dual-forms/memory-motion": {
        "file": "papers/four-dual-forms/memory-motion.html",
        "title": "Memory Motion: Return, Mirror Transfer, and Relative Phase",
        "pdf": "papers/four-dual-forms/pdf/02_memory_motion.pdf",
        "source": "papers/four-dual-forms/source/02_memory_motion.tex",
    },
    "/papers/four-dual-forms/time-scope": {
        "file": "papers/four-dual-forms/time-scope.html",
        "title": "Time Scope: Local Phase and Projective Return",
        "pdf": "papers/four-dual-forms/pdf/03_time_scope.pdf",
        "source": "papers/four-dual-forms/source/03_time_scope.tex",
    },
    "/papers/four-dual-forms/horizon-silence": {
        "file": "papers/four-dual-forms/horizon-silence.html",
        "title": "Horizon Silence: Recognition at the Boundary of Type",
        "pdf": "papers/four-dual-forms/pdf/04_horizon_silence.pdf",
        "source": "papers/four-dual-forms/source/04_horizon_silence.tex",
    },
}
VERIFIER = "papers/four-dual-forms/source/verify_four_papers_v0_3.py"
RECEIPT = "verification/four-dual-forms/verify_four_papers_v0_3.out"
CLAIM_REGISTER = "research/four-dual-forms-v0.3.json"
DOI = "10.5281/zenodo.24073596"


def load_r51():
    target = ROOT / "tools/build_r51_exact_read.py"
    spec = importlib.util.spec_from_file_location("r51", target)
    if spec is None or spec.loader is None:
        raise RuntimeError("Cannot load the R51.1 publication builder.")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


r51 = load_r51()
require = r51.require


def read_lastmods() -> dict[str, str]:
    value = json.loads((ROOT / LASTMOD_SOURCE).read_text(encoding="utf-8"))
    require(value["edition"] == RELEASE, "Wrong sitemap lastmod source edition.")
    require(re.fullmatch(r"\d{4}-\d{2}-\d{2}", value["issued"]) is not None,
            "Invalid R52 issue date.")
    routes = value["routes"]
    require(isinstance(routes, dict) and routes, "Sitemap lastmod routes missing.")
    for route, date in routes.items():
        require(route.startswith("/"), f"Non-route lastmod key: {route}")
        require(re.fullmatch(r"\d{4}-\d{2}-\d{2}", date) is not None,
                f"Invalid lastmod date for {route}")
    return routes


def write_redirects(redirects: dict[str, str]) -> None:
    path = ROOT / "_redirects"
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        permitted = ("# R51 canonical aliases;", REDIRECT_HEADER)
        require(not existing.strip() or existing.startswith(permitted),
                "Existing _redirects is not a generated R51/R52 inventory.")
    text = REDIRECT_HEADER + "\n"
    text += "# Explicit file aliases only; folder slash conventions are otherwise preserved.\n"
    text += "".join(f"{source}  {target}  301!\n" for source, target in sorted(redirects.items()))
    r51.write_changed(path, text)


def write_sitemap(urls: set[str], lastmods: dict[str, str]) -> None:
    ET.register_namespace("", r51.SITEMAP_NS)
    root = ET.Element(f"{{{r51.SITEMAP_NS}}}urlset")
    for url in sorted(urls):
        node = ET.SubElement(root, f"{{{r51.SITEMAP_NS}}}url")
        ET.SubElement(node, f"{{{r51.SITEMAP_NS}}}loc").text = url
        date = lastmods.get(urlsplit(url).path)
        if date is not None:
            ET.SubElement(node, f"{{{r51.SITEMAP_NS}}}lastmod").text = date
    r51.write_changed(ROOT / "sitemap.xml", ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n")


def meta_values(page: r51.Page, name: str) -> list[str]:
    return [attrs.get("content", "") for _, _, _, tag, attrs in page.tags
            if tag == "meta" and (attrs.get("name") or "").lower() == name.lower()]


def jsonld_values(page: r51.Page) -> list[object]:
    return [json.loads(page.text[start:end]) for start, end in page.json_spans]


def verify_local_url(url: str, expected: Path) -> None:
    require(r51.local_reference(url) == expected,
            f"Local link differs from declared path: {url}")
    require(expected.is_file(), f"Missing local target: {expected.relative_to(ROOT)}")


def validate_routes(pages, owners, aliases, lastmods: dict[str, str]) -> dict:
    for path in pages:
        parsed = r51.Page(path.read_text(encoding="utf-8"))
        canonicals = parsed.canonical_tags()
        require(len(canonicals) == 1, f"Expected one canonical link: {path}")
        require(canonicals[0][4].get("href") == BASE + r51.canonical_route(path),
                f"Incorrect canonical URL: {path}")
        for _, _, _, tag, attrs in parsed.tags:
            if "href" not in attrs or attrs["href"] is None:
                continue
            if tag == "link" and "canonical" in (attrs.get("rel") or "").lower().split():
                continue
            value = attrs["href"]
            require(r51.normalized_html_url(value, path, aliases, absolute=False) == value,
                    f"Noncanonical internal HTML href: {path.relative_to(ROOT)}: {value}")
        for start, end in parsed.json_spans:
            value = json.loads(parsed.text[start:end])
            require(r51.normalized_jsonld(value, path, aliases) == value,
                    f"Noncanonical JSON-LD URL: {path.relative_to(ROOT)}")
    redirects = {}
    for number, line in enumerate((ROOT / "_redirects").read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = line.split()
        require(len(parts) == 3 and parts[2] == "301!", f"Unexpected redirect rule on line {number}")
        source, target, _ = parts
        require(source not in redirects, f"Duplicate redirect source: {source}")
        redirects[source] = target
    require(redirects == r51.redirect_map(pages), "Redirect inventory differs from canonical aliases.")
    r51.validate_redirect_graph(redirects)
    expected, duplicates = r51.sitemap_entries(owners)
    tree = ET.parse(ROOT / "sitemap.xml")
    require(tree.getroot().tag == f"{{{r51.SITEMAP_NS}}}urlset", "Invalid sitemap root.")
    nodes = tree.findall(f"{{{r51.SITEMAP_NS}}}url")
    actual = [node.findtext(f"{{{r51.SITEMAP_NS}}}loc") for node in nodes]
    require(len(actual) == len(set(actual)), "Duplicate sitemap URL.")
    require(set(actual) == expected, "Sitemap differs from indexable HTML and unique PDFs.")
    observed = {}
    for node in nodes:
        url = node.findtext(f"{{{r51.SITEMAP_NS}}}loc")
        mods = node.findall(f"{{{r51.SITEMAP_NS}}}lastmod")
        require(len(mods) <= 1, f"Duplicate sitemap lastmod: {url}")
        if mods:
            observed[urlsplit(url).path] = mods[0].text
        route = urlsplit(url).path
        path = owners.get(route, r51.local_reference(url))
        require(path.is_file(), f"Sitemap target is missing: {url}")
    require(observed == lastmods, "Sitemap lastmod values differ from the R52 source declaration.")
    return {"html_files": len(pages), "canonical_html_routes": len(owners), "redirects": len(redirects), "sitemap_urls": len(actual), "lastmod_routes": len(observed), "byte_identical_pdf_aliases_omitted": duplicates}


def validate_paper_records(owners: dict[str, Path]) -> None:
    expected_author = "Coppa, Anthony Vito"
    for route, record in PAPERS.items():
        path = owners.get(route)
        require(path == ROOT / record["file"], f"Wrong page owner for {route}")
        page = r51.Page(path.read_text(encoding="utf-8"))
        expected_meta = {
            "citation_title": record["title"],
            "citation_author": expected_author,
            "citation_publication_date": "2026/11/10",
            "citation_doi": DOI,
            "citation_pdf_url": BASE + "/" + record["pdf"],
            "citation_abstract_html_url": BASE + route,
        }
        for name, value in expected_meta.items():
            require(meta_values(page, name) == [value], f"Bad {name} on {record['file']}")
        graphs = [value.get("@graph", []) for value in jsonld_values(page) if isinstance(value, dict)]
        graph = [item for items in graphs for item in items]
        article = next((item for item in graph if item.get("@type") == "ScholarlyArticle"), None)
        code = next((item for item in graph if item.get("@type") == "SoftwareSourceCode"), None)
        require(article is not None and code is not None, f"Missing article or code JSON-LD: {record['file']}")
        require(article.get("headline") == record["title"], f"Wrong article title: {record['file']}")
        require(article.get("url") == BASE + route, f"Wrong article URL: {record['file']}")
        require(article.get("identifier", {}).get("value") == DOI, f"Wrong DOI record: {record['file']}")
        require(code.get("url") == BASE + "/" + VERIFIER, f"Wrong verifier URL: {record['file']}")
        verify_local_url(expected_meta["citation_pdf_url"], ROOT / record["pdf"])
        verify_local_url(article["isBasedOn"], ROOT / record["source"])
        verify_local_url(code["url"], ROOT / VERIFIER)
        require((ROOT / RECEIPT).is_file() and (ROOT / CLAIM_REGISTER).is_file(), "Missing shared record target.")
    home = r51.Page((ROOT / "index.html").read_text(encoding="utf-8"))
    require(meta_values(home, "citation_author") == [expected_author], "Homepage citation author is not normalized.")
    author = (ROOT / "anthony-vito-coppa.html").read_text(encoding="utf-8")
    require("research/verification-manifest-v0.2.json" in author, "Author page has stale manifest pointer.")
    require("verification-manifest-v0.1.json\">verification manifest" not in author, "Author page retains stale visible manifest pointer.")
    library = (ROOT / "library.html").read_text(encoding="utf-8")
    for route in PAPERS:
        require(route.removeprefix("/") in library, f"Library lacks paper record: {route}")
    for machine_file in ("llms.txt", "llms-full.txt"):
        value = (ROOT / machine_file).read_text(encoding="utf-8")
        require("verification-manifest-v0.2.json" in value, f"Stale machine manifest: {machine_file}")
        for route in PAPERS:
            require(BASE + route in value, f"Machine map lacks record: {machine_file}: {route}")
    robots = (ROOT / "robots.txt").read_text(encoding="utf-8")
    for marker in ("User-agent: OAI-SearchBot", "User-agent: *", "Allow: /", f"Sitemap: {BASE}/sitemap.xml"):
        require(marker in robots, f"Robots policy missing: {marker}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--validate-only", action="store_true", help="Read and check; write no files.")
    args = parser.parse_args()
    lastmods = read_lastmods()
    pages, owners, aliases = r51.page_inventory()
    summary = {"mode": "validate" if args.validate_only else "build", "website_release": RELEASE}
    if not args.validate_only:
        summary["html_files_changed"] = r51.normalize_html(pages, aliases)
        write_redirects(r51.redirect_map(pages))
        urls, _ = r51.sitemap_entries(owners)
        write_sitemap(urls, lastmods)
        r51.write_checksums()
    summary.update(validate_routes(pages, owners, aliases, lastmods))
    r51.validate_integrity()
    validate_paper_records(owners)
    summary["sha256sum_payload_files"] = r51.validate_checksums()
    summary["paper_records"] = len(PAPERS)
    summary["result"] = "PASS"
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, KeyError, OSError, json.JSONDecodeError, ET.ParseError, RuntimeError) as error:
        print(f"R52 discovery validation FAILED: {error}", file=sys.stderr)
        raise SystemExit(1)
